import AppKit

/// Watches the general pasteboard and reports each new copy. macOS has no notification for
/// pasteboard changes, so it polls `changeCount`, which is cheap.
@MainActor
final class ClipboardMonitor {
    static let interval: TimeInterval = 0.5

    /// Types that mark a copy as not for keeping: passwords and other secrets, and contents
    /// apps write for a moment or make up themselves (nspasteboard.org).
    static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        // Copied files, which aren't kept: their string is just the file name.
        .fileURL,
    ]

    /// Called with each copy worth keeping. Images come as whatever the pasteboard holds;
    /// `png(from:)` converts them.
    var onCopy: (Content) -> Void = { _ in }

    enum Content: Sendable {
        case text(String)
        case image(Data, NSPasteboard.PasteboardType)
    }

    private let pasteboard: NSPasteboard
    private var timer: Timer?
    private var changeCount = 0

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    /// Starts watching. What's on the pasteboard already isn't reported.
    func start() {
        guard timer == nil else { return }
        changeCount = pasteboard.changeCount
        let timer = Timer(timeInterval: Self.interval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != changeCount else { return }
        changeCount = count
        if let content = Self.content(of: pasteboard) { onCopy(content) }
    }

    /// Whether a copy with these types is kept.
    static func shouldRecord(_ types: [NSPasteboard.PasteboardType]) -> Bool {
        !types.isEmpty && ignoredTypes.isDisjoint(with: types)
    }

    /// Text, preferred when there is some that isn't blank, or else an image.
    static func content(of pasteboard: NSPasteboard) -> Content? {
        guard let types = pasteboard.types, shouldRecord(types) else { return nil }
        if let text = pasteboard.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return .text(text)
        }
        for type in [NSPasteboard.PasteboardType.png, .tiff] {
            if let data = pasteboard.data(forType: type) { return .image(data, type) }
        }
        return nil
    }

    /// `data` of `type` as PNG. Slow for big images, so call it off the main actor.
    nonisolated static func png(from data: Data, type: NSPasteboard.PasteboardType) -> Data? {
        if type == .png { return data }
        return NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:])
    }
}
